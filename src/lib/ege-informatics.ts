export interface PlanBlock {
  section: string;
  topics: string[];
  events: { title: string; kind: EventKind }[];
}

/** Делит план на блоки: каждый блок заканчивается одной или несколькими контрольными точками подряд */
export function planBlocks(plan: PlanItem[] = EGE_INF_PLAN): PlanBlock[] {
  const blocks: PlanBlock[] = [];
  let cur: PlanBlock = { section: "", topics: [], events: [] };
  for (const item of plan) {
    if (typeof item === "string") {
      if (cur.events.length) {
        blocks.push(cur);
        cur = { section: "", topics: [], events: [] };
      }
      cur.topics.push(item);
    } else cur.events.push({ title: item.event, kind: item.kind });
  }
  if (cur.topics.length || cur.events.length) blocks.push(cur);
  blocks.forEach((b, i) => {
    b.section = b.events.length ? `Блок ${i + 1} → ${b.events.map((e) => e.title).join(" и ")}` : `Блок ${i + 1}`;
  });
  return blocks;
}
